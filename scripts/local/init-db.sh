#!/usr/bin/env bash
# Create a NEW dedicated kit database for local review. Touches nothing else.
# Refuses if the database already exists unless --reset is passed.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

DB_NAME="${FF_DB_NAME:-floorfunds_local}"
DB_ROLE="${FF_DB_ROLE:-$DB_NAME}"
DB_HOST="${FF_DB_HOST:-127.0.0.1}"
DB_PORT="${FF_DB_PORT:-5432}"
ADMIN_USER="${FF_PG_SUPERUSER:-postgres}"
RESET=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --reset|-Reset) RESET=1; shift ;;
    --db) DB_NAME="$2"; DB_ROLE="${FF_DB_ROLE:-$2}"; shift 2 ;;
    --role) DB_ROLE="$2"; shift 2 ;;
    --host) DB_HOST="$2"; shift 2 ;;
    --port) DB_PORT="$2"; shift 2 ;;
    --superuser) ADMIN_USER="$2"; shift 2 ;;
    -h|--help)
      cat <<EOF
Usage: scripts/local/init-db.sh [--reset] [--db NAME] [--role NAME] [--host H] [--port P]
  Creates kit database \$DB (default floorfunds_local) via db/setup.sh --seed,
  then loads scripts/local/review-seed.sql.
  Refuses if the database already exists unless --reset.
  Passwords: FF_DB_PASSWORD / FF_ADMIN_API_PASSWORD / FF_LOGIN_PASSWORD / FF_ISSUER_PASSWORD
  or generated into \$FF_LOCAL_DIR/secrets.env (0600). Never printed.
EOF
      exit 0
      ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

LOCAL_DIR="${FF_LOCAL_DIR:-$ROOT/.local-run}"
mkdir -p "$LOCAL_DIR"
umask 077

PSQL_SUPER=(psql -h "$DB_HOST" -p "$DB_PORT" -U "$ADMIN_USER" -d postgres -v ON_ERROR_STOP=1)
if ! command -v psql >/dev/null; then
  echo "psql not on PATH. Install PostgreSQL client tools and retry." >&2
  exit 3
fi

exists="$("${PSQL_SUPER[@]}" -tAc "SELECT 1 FROM pg_database WHERE datname = '$DB_NAME'" | tr -d '[:space:]')"
if [[ "$exists" == "1" && "$RESET" -ne 1 ]]; then
  echo "Refused: database $DB_NAME already exists. Re-run with --reset to drop and recreate it (kit-marked only via setup.sh --force --drop)." >&2
  exit 5
fi

gen_pw() { od -An -N18 -tx1 /dev/urandom | tr -d ' \n'; }
if [[ -z "${FF_DB_PASSWORD:-}" ]]; then export FF_DB_PASSWORD="$(gen_pw)"; fi
if [[ -z "${FF_ADMIN_API_PASSWORD:-}" ]]; then export FF_ADMIN_API_PASSWORD="$(gen_pw)"; fi
if [[ -z "${FF_LOGIN_PASSWORD:-}" ]]; then export FF_LOGIN_PASSWORD="$(gen_pw)"; fi
if [[ -z "${FF_ISSUER_PASSWORD:-}" ]]; then export FF_ISSUER_PASSWORD="$(gen_pw)"; fi

SECRETS="$LOCAL_DIR/secrets.env"
cat > "$SECRETS" <<EOF
# Generated by scripts/local/init-db.sh — do not commit
FF_DB_NAME='$DB_NAME'
FF_DB_ROLE='$DB_ROLE'
FF_DB_HOST='$DB_HOST'
FF_DB_PORT='$DB_PORT'
FF_DB_PASSWORD='$FF_DB_PASSWORD'
FF_ADMIN_API_PASSWORD='$FF_ADMIN_API_PASSWORD'
FF_LOGIN_PASSWORD='$FF_LOGIN_PASSWORD'
FF_ISSUER_PASSWORD='$FF_ISSUER_PASSWORD'
CONNECTION_STRING='Host=${DB_HOST};Port=${DB_PORT};Database=${DB_NAME};Username=${DB_ROLE};Password=${FF_DB_PASSWORD}'
ADMIN_API_CONNECTION_STRING='Host=${DB_HOST};Port=${DB_PORT};Database=${DB_NAME};Username=${DB_NAME}_admin_api;Password=${FF_ADMIN_API_PASSWORD}'
LOGIN_CONNECTION_STRING='Host=${DB_HOST};Port=${DB_PORT};Database=${DB_NAME};Username=${DB_NAME}_login;Password=${FF_LOGIN_PASSWORD}'
ISSUER_CONNECTION_STRING='Host=${DB_HOST};Port=${DB_PORT};Database=${DB_NAME};Username=${DB_NAME}_issuer;Password=${FF_ISSUER_PASSWORD}'
AUTH_CHECKS_DB='$DB_NAME'
EOF
chmod 600 "$SECRETS"

SETUP_FLAGS=(--db "$DB_NAME" --role "$DB_ROLE" --host "$DB_HOST" --port "$DB_PORT" --force --seed)
if [[ "$RESET" -eq 1 && "$exists" == "1" ]]; then
  SETUP_FLAGS+=(--drop)
fi

# Superuser: prefer peer auth on socket when host is loopback.
EXTRA=()
if [[ "$DB_HOST" == "127.0.0.1" || "$DB_HOST" == "localhost" ]]; then
  EXTRA+=(--admin-host "")
  if id postgres >/dev/null 2>&1; then
    EXTRA+=(--superuser-cmd "sudo -u postgres psql -p ${DB_PORT}")
  else
    EXTRA+=(--superuser-cmd "psql -p ${DB_PORT}")
  fi
else
  EXTRA+=(--admin-host "$DB_HOST" --superuser-cmd "psql -h ${DB_HOST} -p ${DB_PORT} -U ${ADMIN_USER}")
fi

echo "Running db/setup.sh ${SETUP_FLAGS[*]} ${EXTRA[*]} ..."
bash db/setup.sh "${SETUP_FLAGS[@]}" "${EXTRA[@]}"

# Issuer URL used by review seed (overridden again by start.sh to the live stand-in URL).
ISS="${STANDIN_ISSUER:-http://127.0.0.1:5099/standin}"
echo "Loading scripts/local/review-seed.sql as superuser (issuer=$ISS) ..."
# FORCE RLS blocks the kit owner from inserting locations/clients; superuser + row_security=off is required.
if id postgres >/dev/null 2>&1 && [[ "$DB_HOST" == "127.0.0.1" || "$DB_HOST" == "localhost" ]]; then
  sudo -u postgres psql -p "$DB_PORT" -d "$DB_NAME" \
    -v ON_ERROR_STOP=1 -v iss="$ISS" -f "$ROOT/scripts/local/review-seed.sql"
else
  PGPASSWORD="${PGPASSWORD:-}" psql -h "$DB_HOST" -p "$DB_PORT" -U "$ADMIN_USER" -d "$DB_NAME" \
    -v ON_ERROR_STOP=1 -v iss="$ISS" -f "$ROOT/scripts/local/review-seed.sql"
fi

echo "Local DB ready: $DB_NAME on $DB_HOST:$DB_PORT"
echo "Secrets written to $SECRETS (mode 0600). Passwords are not printed."
