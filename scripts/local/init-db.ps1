#Requires -Version 7.0
<#
.SYNOPSIS
  Create a NEW dedicated kit database for local review (Windows-first).
.DESCRIPTION
  Refuses if the database already exists unless -Reset.
  Passwords come from env FF_*_PASSWORD or are generated into .local-run/secrets.env.
  Never prints passwords. Never commits secrets.
#>
param(
  [string]$Db = $(if ($env:FF_DB_NAME) { $env:FF_DB_NAME } else { 'floorfunds_local' }),
  [string]$Role = $(if ($env:FF_DB_ROLE) { $env:FF_DB_ROLE } elseif ($env:FF_DB_NAME) { $env:FF_DB_NAME } else { 'floorfunds_local' }),
  [Alias('Host')][string]$DbHost = $(if ($env:FF_DB_HOST) { $env:FF_DB_HOST } else { '127.0.0.1' }),
  [int]$Port = $(if ($env:FF_DB_PORT) { [int]$env:FF_DB_PORT } else { 5432 }),
  [string]$Superuser = $(if ($env:FF_PG_SUPERUSER) { $env:FF_PG_SUPERUSER } else { 'postgres' }),
  [switch]$Reset
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Set-Location $Root

$LocalDir = if ($env:FF_LOCAL_DIR) { $env:FF_LOCAL_DIR } else { Join-Path $Root '.local-run' }
New-Item -ItemType Directory -Force -Path $LocalDir | Out-Null

function New-LocalPassword {
  $bytes = New-Object byte[] 18
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $_.ToString('x2') })
}

$psql = Get-Command psql -ErrorAction SilentlyContinue
if (-not $psql) { Write-Error 'psql not on PATH. Install PostgreSQL client tools (winget install PostgreSQL.PostgreSQL).'; exit 3 }

$exists = (& psql -h $DbHost -p $Port -U $Superuser -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$Db'").Trim()
if ($exists -eq '1' -and -not $Reset) {
  Write-Error "Refused: database $Db already exists. Re-run with -Reset to drop and recreate (kit-marked only)."
  exit 5
}

if (-not $env:FF_DB_PASSWORD) { $env:FF_DB_PASSWORD = New-LocalPassword }
if (-not $env:FF_ADMIN_API_PASSWORD) { $env:FF_ADMIN_API_PASSWORD = New-LocalPassword }
if (-not $env:FF_LOGIN_PASSWORD) { $env:FF_LOGIN_PASSWORD = New-LocalPassword }
if (-not $env:FF_ISSUER_PASSWORD) { $env:FF_ISSUER_PASSWORD = New-LocalPassword }

$secrets = Join-Path $LocalDir 'secrets.env'
@(
  "# Generated by scripts/local/init-db.ps1 — do not commit"
  "FF_DB_NAME='$Db'"
  "FF_DB_ROLE='$Role'"
  "FF_DB_HOST='$DbHost'"
  "FF_DB_PORT='$Port'"
  "FF_DB_PASSWORD='$($env:FF_DB_PASSWORD)'"
  "FF_ADMIN_API_PASSWORD='$($env:FF_ADMIN_API_PASSWORD)'"
  "FF_LOGIN_PASSWORD='$($env:FF_LOGIN_PASSWORD)'"
  "FF_ISSUER_PASSWORD='$($env:FF_ISSUER_PASSWORD)'"
  "CONNECTION_STRING='Host=${DbHost};Port=${Port};Database=${Db};Username=${Role};Password=$($env:FF_DB_PASSWORD)'"
  "ADMIN_API_CONNECTION_STRING='Host=${DbHost};Port=${Port};Database=${Db};Username=${Db}_admin_api;Password=$($env:FF_ADMIN_API_PASSWORD)'"
  "LOGIN_CONNECTION_STRING='Host=${DbHost};Port=${Port};Database=${Db};Username=${Db}_login;Password=$($env:FF_LOGIN_PASSWORD)'"
  "ISSUER_CONNECTION_STRING='Host=${DbHost};Port=${Port};Database=${Db};Username=${Db}_issuer;Password=$($env:FF_ISSUER_PASSWORD)'"
  "AUTH_CHECKS_DB='$Db'"
) | Set-Content -LiteralPath $secrets -Encoding utf8
# Restrict ACL to current user (Windows equivalent of 0600)
icacls $secrets /inheritance:r /grant:r "$($env:USERNAME):(R,W)" | Out-Null

$setupArgs = @('-File', (Join-Path $Root 'db\setup.ps1'), '-Db', $Db, '-Role', $Role, '-DbHost', $DbHost, '-Port', $Port, '-Force', '-Seed', '-AdminUser', $Superuser, '-AdminHost', $DbHost)
if ($Reset -and $exists -eq '1') { $setupArgs += '-Drop' }

Write-Host "Running db/setup.ps1 ..."
& pwsh @setupArgs
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$iss = if ($env:STANDIN_ISSUER) { $env:STANDIN_ISSUER } else { 'http://127.0.0.1:5099/standin' }
Write-Host "Loading scripts/local/review-seed.sql as superuser (FORCE RLS) ..."
# Kit owner cannot INSERT locations under FORCE RLS; use the Postgres superuser.
$env:PGPASSWORD = $env:PGPASSWORD
& psql -h $DbHost -p $Port -U $Superuser -d $Db -v ON_ERROR_STOP=1 -v "iss=$iss" -f (Join-Path $Root 'scripts\local\review-seed.sql')
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host "Local DB ready: $Db on ${DbHost}:$Port"
Write-Host "Secrets written to $secrets (ACL restricted). Passwords are not printed."
