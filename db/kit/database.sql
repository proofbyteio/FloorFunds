SELECT set_config('floorfunds_kit.db', :'db', true) AS kit_db, set_config('floorfunds_kit.role', :'role', true) AS kit_role,
       set_config('floorfunds_kit.new', :'kit_new', true) AS kit_new2 \gset
DO $kit$
DECLARE
  db  text := current_setting('floorfunds_kit.db');
  ro  text := current_setting('floorfunds_kit.role');
  new boolean := current_setting('floorfunds_kit.new')::boolean;
  c   text;
BEGIN
  SELECT shobj_description(oid, 'pg_database') INTO c FROM pg_database
   WHERE datname = db AND NOT datistemplate AND pg_get_userbyid(datdba)::text = ro
     AND NOT (SELECT rolsuper FROM pg_roles WHERE oid = datdba);
  IF NOT FOUND OR NOT ((new AND c IS NULL) OR c IS NOT DISTINCT FROM 'floorfunds-kit') THEN
    RAISE EXCEPTION 'floorfunds-kit: refusing to touch a database the kit did not create (no marker, wrong or superuser owner, or a template)';
  END IF;
  IF new THEN EXECUTE format('COMMENT ON DATABASE %I IS %L', db, 'floorfunds-kit'); END IF;
  EXECUTE format('REVOKE CONNECT ON DATABASE %I FROM PUBLIC', db);
  -- SA L3. Nothing in this repo creates a temporary table. TEMP stays revoked
  -- from PUBLIC. The owner, admin_api, and login are not granted it back.
  EXECUTE format('REVOKE TEMP ON DATABASE %I FROM PUBLIC', db);
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO %I', db, ro);
END
$kit$;
COMMIT;
