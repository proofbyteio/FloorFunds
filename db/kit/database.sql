SELECT set_config('floorfunds_kit.db', :'db', false) AS kit_db, set_config('floorfunds_kit.role', :'role', false) AS kit_role \gset
DO $kit$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = current_setting('floorfunds_kit.db') AND NOT datistemplate
                   AND pg_get_userbyid(datdba)::text = current_setting('floorfunds_kit.role')
                   AND NOT (SELECT rolsuper FROM pg_roles WHERE oid = datdba)
                   AND shobj_description(oid, 'pg_database') IS NOT DISTINCT FROM 'floorfunds-kit') THEN
    RAISE EXCEPTION 'floorfunds-kit: refusing to touch a database the kit did not create (no marker, wrong or superuser owner, or a template)';
  END IF;
END
