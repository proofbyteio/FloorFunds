#!/usr/bin/env bash
# create-app-roles.sh <db> — superuser step for S2a (spec §8.2). Creates the two per-DB app roles if missing:
#   <db>_admin_api, <db>_login : LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION, own nothing.
# The EF migration grants to them and RAISEs if they are missing. Passwords are generated test-only values kept in
# /tmp/ff-db/<db>_roles.env (0600, never committed, never printed). Test boxes only (ff-db.sh databases).
set -euo pipefail
db=${1:?usage: create-app-roles.sh <db>}
[[ "$db" =~ ^ff_[a-z0-9_]+$ ]] || { echo "refuse: db name must match ^ff_[a-z0-9_]+$ (test DBs only)" >&2; exit 2; }
dir=/tmp/ff-db; env="$dir/${db}_roles.env"
install -d -m 0700 "$dir"; umask 077
if [[ -f "$env" ]]; then
  pa=$(sed -n 's/^ADMIN_API_PASSWORD=//p' "$env"); pl=$(sed -n 's/^LOGIN_PASSWORD=//p' "$env")
  [[ "$pa" =~ ^[0-9a-f]{48}$ && "$pl" =~ ^[0-9a-f]{48}$ ]] || { echo "refuse: $env is malformed" >&2; exit 2; }
else
  pa=$(openssl rand -hex 24); pl=$(openssl rand -hex 24)
fi
for pair in "${db}_admin_api:$pa" "${db}_login:$pl"; do
  r=${pair%%:*}; p=${pair#*:}
  sudo -u postgres psql -X -q -v ON_ERROR_STOP=1 -d postgres -v r="$r" -v p="$p" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION INHERIT', :'r', :'p')
 WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'r') \gexec
SELECT format('ALTER ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION', :'r', :'p') \gexec
SQL
done
cat > "$env.tmp" <<E
# test-only, generated by create-app-roles.sh; never commit
ADMIN_API_PASSWORD=$pa
LOGIN_PASSWORD=$pl
ADMIN_API_CONNECTION_STRING="Host=127.0.0.1;Port=5432;Database=$db;Username=${db}_admin_api;Password=$pa"
LOGIN_CONNECTION_STRING="Host=127.0.0.1;Port=5432;Database=$db;Username=${db}_login;Password=$pl"
E
chmod 0600 "$env.tmp"; mv "$env.tmp" "$env"
echo "ok: roles ${db}_admin_api, ${db}_login (credentials in $env)"
