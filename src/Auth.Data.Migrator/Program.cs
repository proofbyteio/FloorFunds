// S2a migration runner (TLD 2026-11-04 7:56 option b; replaces dotnet-ef). Owner connection string from env
// CONNECTION_STRING (never printed). Commands:
//   update [target]   MigrateAsync to latest, or to <target> ("0" = revert everything)
//   list              applied / pending migrations
//   script <path>     idempotent SQL script of all migrations (IMigrator.GenerateScript, Idempotent) -> <path>
using Auth.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

var cmd = args.Length > 0 ? args[0] : "";
var cs = Environment.GetEnvironmentVariable("CONNECTION_STRING");
if (cmd == "script")
{
    if (args.Length != 2) return Usage();
    // GenerateScript needs the provider, not a live database; a placeholder keeps secrets out of this path.
    await using var sdb = new AuthDbContext(AuthDb.Options(cs ?? "Host=placeholder;Database=placeholder"));
    var sql = sdb.GetService<IMigrator>().GenerateScript(fromMigration: null, toMigration: null, MigrationsSqlGenerationOptions.Idempotent);
    var header = "-- GENERATED by src/Auth.Data.Migrator (`script`) from the hand-written EF migrations in src/Auth.Data/Migrations.\n" +
                 "-- Do not edit. Idempotent: safe to run twice. Run as the DB owner AFTER src/Auth.Data/tools/create-app-roles.sh.\n" +
                 "-- Spec: contract/v1.1-S2a-location-login-config.md section 8.\n";
    await File.WriteAllTextAsync(args[1], header + sql.Replace("\r\n", "\n"));
    Console.WriteLine($"script: wrote {args[1]}");
    return 0;
}
if (string.IsNullOrEmpty(cs)) { Console.Error.WriteLine("CONNECTION_STRING is not set"); return 2; }
await using var db = new AuthDbContext(AuthDb.Options(cs));
switch (cmd)
{
    case "update":
        var target = args.Length > 1 ? args[1] : null;
        await db.Database.MigrateAsync(target);
        Console.WriteLine($"update: ok (target {target ?? "latest"})");
        break;
    case "list":
        foreach (var m in await db.Database.GetAppliedMigrationsAsync()) Console.WriteLine($"applied {m}");
        foreach (var m in await db.Database.GetPendingMigrationsAsync()) Console.WriteLine($"pending {m}");
        break;
    default:
        return Usage();
}
return 0;

static int Usage() { Console.Error.WriteLine("usage: Auth.Data.Migrator update [target|0] | list | script <path>"); return 2; }
